// Decompile selected function entry points to one auditable text file.
// @category KartRiderDemoPhysics

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;

import java.io.BufferedWriter;
import java.io.File;
import java.io.FileWriter;

public class DecompileFunctions extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 2) {
            throw new IllegalArgumentException(
                "Usage: DecompileFunctions.java <output-file> <address> [address ...]");
        }

        File output = new File(args[0]);
        File parent = output.getParentFile();
        if (parent != null && !parent.exists() && !parent.mkdirs()) {
            throw new IllegalStateException("Cannot create output directory: " + parent);
        }

        DecompInterface decompiler = new DecompInterface();
        decompiler.toggleCCode(true);
        decompiler.toggleSyntaxTree(true);
        decompiler.setSimplificationStyle("decompile");
        if (!decompiler.openProgram(currentProgram)) {
            throw new IllegalStateException("Could not open program in decompiler");
        }

        try (BufferedWriter writer = new BufferedWriter(new FileWriter(output))) {
            writer.write("Selected KartRider.exe decompilations\n");
            writer.write("Generated by Ghidra; names and types remain provisional.\n\n");

            for (int i = 1; i < args.length; i++) {
                Address requested = toAddr(args[i]);
                Function function = currentProgram.getFunctionManager()
                    .getFunctionContaining(requested);

                writer.write("================================================================================\n");
                writer.write("REQUESTED " + requested + "\n");
                if (function == null) {
                    writer.write("No containing function.\n\n");
                    continue;
                }

                writer.write("ENTRY " + function.getEntryPoint() + "\n");
                writer.write("NAME " + function.getName(true) + "\n");
                writer.write("SIGNATURE " + function.getSignature() + "\n");
                writer.write("BODY " + function.getBody() + "\n\n");

                DecompileResults result = decompiler.decompileFunction(function, 120, monitor);
                if (!result.decompileCompleted()) {
                    writer.write("DECOMPILATION FAILED: " + result.getErrorMessage() + "\n\n");
                    continue;
                }
                writer.write(result.getDecompiledFunction().getC());
                writer.write("\n\n");
            }
        } finally {
            decompiler.dispose();
        }

        println("Wrote selected decompilations: " + output.getAbsolutePath());
    }
}
